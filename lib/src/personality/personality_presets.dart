  static PersonalityProfile create(
    String id,
    String characterId, {
    String? profileId,
    String? name,
  }) {
    final data = _descriptions[id];
    if (data == null) throw const FormatException('未知人格预设');
    final axes = data['axes'] as List<int>;
    final motives = data['motives'] as List<String>;
    final rules = (data['rules'] as List)
        .map((row) => Map<String, Object>.from(row as Map))
        .toList();
    final scenes = (data['scenes'] as List)
        .map((row) => Map<String, Object>.from(row as Map))
        .toList();
    final now = DateTime.now().toUtc().toIso8601String();
    return PersonalityProfile(
      profileId: profileId ?? '$id-${DateTime.now().microsecondsSinceEpoch}',
      name: name ?? names[id]!,
      characterId: characterId,
      presetId: id,
      baseAxes: {'selfOther': axes[0], 'restraintExpression': axes[1]},
      traits: _traits[id]!,
      motives: motives,
      contradictions: [
        for (var i = 0; i < rules.length; i++)
          PersonalityRule(
            id: rules[i]['id'] as String,
            triggerType: rules[i]['trigger'] as String,
            priority: 80 - i,
            surface: data['summary'] as String,
            hiddenNeed: motives[i % motives.length],
            response: rules[i]['text'] as String,
            constraint: '尊重明确拒绝；不能代替用户作决定，不用威胁或惩罚维持关系。',
          ),
      ],
      situations: [
        for (var i = 0; i < scenes.length; i++)
          PersonalityRule(
            id: '${id}_S${i + 1}',
            triggerType: scenes[i]['trigger'] as String,
            priority: 60 - i,
            surface: scenes[i]['surface'] as String,
            response: scenes[i]['response'] as String,
          ),
      ],
      metadata: {
        'createdAt': now,
        'updatedAt': now,
        'summary': data['summary'] as String,
        'style': data['style'] as String,
      },
    );
  }
}

